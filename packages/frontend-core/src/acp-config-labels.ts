export function acpConfigLabel(text: string, language?: string): string {
  if (language !== "zh-CN") return text;
  return chinese[text.trim().toLowerCase()] ?? text;
}
export function acpConfigDescription(
  text: string | null | undefined,
  language?: string,
): string | undefined {
  if (!text) return;
  const translated = acpConfigLabel(text, language);
  // 未知描述保留在协议内；中文设置不混入未翻译的大段英语说明。
  return language === "zh-CN" && translated === text && !/[\u3400-\u9fff]/u.test(text)
    ? undefined
    : translated;
}
